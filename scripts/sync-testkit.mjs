#!/usr/bin/env node
/**
 * Refreshes the vendored plugin testkit (test/vendor/plugin-testkit) from the waterplane checkout,
 * so the suite runs anywhere (CI, a fresh clone) without a sibling repo. The kit files are copied
 * verbatim; only shared.mjs is replaced: upstream it imports the built @waterplane/shared package
 * (a 4.7 MB dist), here it re-exports from ONE tree-shaken bundle made by the checkout's own esbuild.
 * No dependency is added to this repo; esbuild is borrowed from the source checkout at sync time.
 *
 *   npm run sync:testkit            # source: $WATERPLANE_REPO, default ~/dev/waterplane-public
 *
 * The source is a checkout of the PUBLIC waterplane repo (github.com/waterplane-dev/waterplane) at a
 * release tag, so the pin in SOURCE.json is a release anyone can check out and compare.
 *
 * Writes SOURCE.json (source commit + dirty flag, PLUGIN_API_VERSION) so the pin is auditable;
 * test/testkit-pin.test.mjs fails when that version drifts from this plugin's manifest.
 *
 * The bundle's per-module path comments (the source checkout's local layout) are stripped.
 * Everything is built and checked in a temp
 * dir first, so a failed sync leaves the vendored copy as it was, never kit and bundle out of step.
 */
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir, homedir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const SRC = process.env.WATERPLANE_REPO || join(homedir(), "dev", "waterplane-public");
const KIT = join(SRC, "packages/plugin-testkit");
const DIST = join(SRC, "packages/shared/dist/index.js");
const OUT = new URL("../test/vendor/plugin-testkit/", import.meta.url).pathname;
const FILES = ["index.mjs", "fakeapi.mjs", "conformance.mjs", "checks.mjs"];
// What the kit's shared.mjs re-exports: keep in step with it (the bundle test below catches a miss).
const NAMES = [
  "FACT_NAMES", "SOURCE_KEYS_MAX", "SOURCE_TYPED_MAX", "PLUGIN_BACKEND_ID_RE", "PLUGIN_API_VERSION",
  "PLUGIN_HOOK_HOLD_DEFAULT_MS", "PLUGIN_HOOK_HOLD_MAX_MS",
  "manifestProblems", "pluginApiProblem", "bindConversation", "pickBound", "BIND_CONFIRM_MS",
  "SOURCE_COMMANDS_MAX", "SOURCE_COMPACTIONS_MAX", "sourceModeProblem", "sourceCommandsProblems", "sourceSpendProblems",
  "sourceCompactionsProblems", "sourceContextSampleProblems",
  "launchModesProblems", "launchModesOf", "PERMISSION_MODE_NAMES",
  "LEGACY",
];

function die(msg) { console.error(`sync-testkit: ${msg}`); process.exit(1); }
const git = (...a) => execFileSync("git", ["-C", SRC, ...a], { encoding: "utf8" }).trim();

if (!existsSync(KIT)) die(`no testkit at ${KIT} (set WATERPLANE_REPO to the waterplane checkout)`);
if (!existsSync(DIST)) die(`${DIST} is missing: run \`npm run build:shared\` in ${SRC} first`);
const esbuild = join(SRC, "node_modules/.bin/esbuild");
if (!existsSync(esbuild)) die(`${esbuild} is missing: run \`npm install\` in ${SRC} first`);

// A dist older than its sources would be bundled under HEAD's commit, a provenance it does not have.
function newestMtime(dir) {
  let t = 0;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    t = Math.max(t, e.isDirectory() ? newestMtime(p) : statSync(p).mtimeMs);
  }
  return t;
}
const SHARED_SRC = join(SRC, "packages/shared/src");
if (existsSync(SHARED_SRC) && newestMtime(SHARED_SRC) > statSync(DIST).mtimeMs) {
  die(`${DIST} is older than packages/shared/src: run \`npm run build:shared\` in ${SRC} first`);
}

const tmp = mkdtempSync(join(tmpdir(), "testkit-"));
try {
  const STAGE = join(tmp, "out");
  mkdirSync(STAGE);
  for (const f of FILES) copyFileSync(join(KIT, f), join(STAGE, f));
  const license = join(SRC, "LICENSE");
  if (!existsSync(license)) die(`${license} is missing: the vendored copy must carry its license`);
  copyFileSync(license, join(STAGE, "LICENSE"));
  const entry = join(tmp, "entry.mjs");
  writeFileSync(entry, `export { ${NAMES.join(", ")} } from ${JSON.stringify(DIST)};\n`);
  const bundle = join(STAGE, "shared.bundle.mjs");
  execFileSync(esbuild, [entry, "--bundle", "--format=esm", "--platform=node", "--target=node22", "--tree-shaking=true",
    "--legal-comments=none", `--outfile=${bundle}`, "--log-level=warning"], { stdio: "inherit" });
  const head = "// GENERATED by scripts/sync-testkit.mjs from @waterplane/shared (MIT, waterplane): do not edit.\n";
  // esbuild's `// ../<checkout>/packages/shared/dist/x.js` markers name the private checkout's layout.
  const body = readFileSync(bundle, "utf8").split("\n").filter((l) => !/^\/\/ \S*packages\/shared\/dist\//.test(l)).join("\n");
  writeFileSync(bundle, head + body);
  // Every name must really exist in the bundle, else the kit would import undefined at runtime.
  const mod = await import(pathToFileURL(bundle).href);
  const missing = NAMES.filter((n) => mod[n] === undefined);
  if (missing.length) die(`bundle lacks ${missing.join(", ")}: the kit's shared.mjs list moved, update NAMES`);

  writeFileSync(join(STAGE, "shared.mjs"),
`/**
 * Vendored stand-in for the kit's shared.mjs: upstream imports the built @waterplane/shared package;
 * here the same names come from one tree-shaken bundle (shared.bundle.mjs), regenerated by
 * scripts/sync-testkit.mjs. Do not edit by hand.
 */
export {
  ${NAMES.join(", ")},
} from "./shared.bundle.mjs";
`);

  let dirty = false;
  try { dirty = git("status", "--porcelain", "--", "packages/plugin-testkit", "packages/shared").length > 0; } catch {}
  const info = {
    source: "github.com/waterplane-dev/waterplane",
    tag: (() => { try { return git("describe", "--tags", "--exact-match", "HEAD"); } catch { return null; } })(),
    commit: git("rev-parse", "HEAD"),
    dirty,
    kitPath: "packages/plugin-testkit",
    PLUGIN_API_VERSION: mod.PLUGIN_API_VERSION,
    synced: new Date().toISOString().slice(0, 10),
  };
  writeFileSync(join(STAGE, "SOURCE.json"), JSON.stringify(info, null, 2) + "\n");
  const size = statSync(bundle).size;
  // Only now replace the vendored copy, whole.
  mkdirSync(OUT, { recursive: true });
  for (const f of readdirSync(STAGE)) copyFileSync(join(STAGE, f), join(OUT, f));
  console.log(`synced ${FILES.length} kit files + shared.bundle.mjs (${size} bytes) @ ${info.tag ?? info.commit.slice(0, 8)}${dirty ? " (dirty)" : ""}, API ${info.PLUGIN_API_VERSION}`);
} finally { rmSync(tmp, { recursive: true, force: true }); }
